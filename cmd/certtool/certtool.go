var (
	publicCertificate = flag.String("public-certificate", "app.cert", "X.509 public certificate file to generate.")
	privateKey        = flag.String("private-key", "app.key", "Private key file to generate.")

	ca = flag.Bool("ca", false, "Generates a root certificate. Use this to establish a chain of trust with derived certificates.")

	commonName         = flag.String("common-name", "", "Common Name (CN) field of the X.509 certificate subject. Defaults to the --organization value.")
	country            = flag.String("country", "US", "Country (C) field of the X.509 certificate subject (e.g. US, CA, GB).")
	organization       = flag.String("organization", "cloudfra", "Organization (O) field of the X.509 certificate subject.")
	organizationalUnit = flag.String("organizational-unit", "gows", "Organizational Unit (OU) field of the X.509 certificate subject.")
	locality           = flag.String("locality", "Seattle", "Locality (L) field of the X.509 certificate subject, typically the city name.")
	province           = flag.String("province", "WA", "Province or state (ST) field of the X.509 certificate subject.")

	validity  = flag.Duration("validity", time.Hour*24*365, "How long the certificate is valid for, as a Go duration (e.g. 8760h, 720h, 24h).")
	hostnames = flag.String("hostnames", "", "Comma-separated list of hostnames and IP addresses to include as Subject Alternative Names (SANs).")
	keyType   = flag.String("key-type", "RSA-2048", "Key algorithm and length. Supported values: RSA-2048, RSA-4096, ECDSA-224, ECDSA-256, ECDSA-384, ECDSA-521. Default for --code-sign is the profile default.")
	ports     = flag.String("ports", "", "Comma-separated list of ports to include as Subject Alternative Names (SANs). Ports are expanded on the hostnames that are specified.")

	parentPublicCertificate = flag.String("parent-public-certificate", "", "(optional) Parent public certificate. If set, the output certificate will trust the parent.")
	parentPrivateKey        = flag.String("parent-private-key", "", "(optional) Parent private key. Required if -parent-public-certificate is set, private key for the parent public certificate.")

	codeSigning = flag.Bool("code-sign", false, "Generates a code signing certificate for binary signing instead of a TLS certificate.")
	target      = flag.String("target", "", "Platform profile for --code-sign. Values: windows7 (win7/windows8/win8), windows10 (win10), windows11 (win11), linux. Default: windows10.")
	pfxOutput   = flag.String("pfx-output", "codesign.pfx", "Output path for the PKCS#12 (.pfx) file. Used with --code-sign for Windows targets.")
	pfxPassword = flag.String("pfx-password", "", "Password for the PKCS#12 (.pfx) file. Empty means no password.")

	spec       = flag.String("spec", "", "Path to a YAML file specifying certificates to generate. See CertificateSpec for the format.")
	chain      = flag.String("chain", "", "Generate a certificate hierarchy from the number of certificates per layer. A single number produces that many standalone leaf certificates (e.g. 3). Comma-separated numbers set the width of each layer from the root down, the last being the leaves (e.g. 1,1 = root CA and leaf; 1,2,3 = 1 root, 2 intermediates per root, 3 leaves per intermediate).")
	namePrefix = flag.String("name-prefix", "", "Prefix placed in front of the common name of every certificate generated by --chain (e.g. prod). Empty by default.")
	outputDir  = flag.String("output-dir", ".", "Output directory for certificates generated by --spec or --chain.")
	exportSpec = flag.String("export-spec", "", "Export the certificate spec as a YAML file instead of generating certificates. Works with --chain or flag-based mode.")

	useYubiKey           = flag.Bool("yubikey", false, "Sign with the root CA stored on a YubiKey instead of --parent-public-certificate/--parent-private-key. Applies to single certificates, --chain, and --spec, whose top-level certificates are signed by the YubiKey.")
	yubiKeyGenerateRoot  = flag.Bool("yubikey-generate-root", false, "Generate a root CA key on a YubiKey and store its self-signed certificate there. The public certificate is also written to --public-certificate; the private key never leaves the YubiKey. Uses the subject, --validity, and --key-type flags (ECDSA-256, ECDSA-384, RSA-2048, or RSA-4096).")
	yubiKeySerial        = flag.String("yubikey-serial", "", "Serial number of the YubiKey to use. Required only when more than one YubiKey is connected.")
	yubiKeySlot          = flag.String("yubikey-slot", yubikey.DefaultSlot, "PIV slot holding the YubiKey root CA: 9a, 9c, 9d, 9e, or 82 through 95.")
	yubiKeyPIN           = flag.String("yubikey-pin", "", "YubiKey PIN. Defaults to the "+yubiKeyPINEnv+" environment variable, otherwise it is prompted for.")
	yubiKeyManagementKey = flag.String("yubikey-management-key", "", "YubiKey management key in hex, needed by --yubikey-generate-root. Defaults to the "+yubiKeyManagementKeyEnv+" environment variable, otherwise the PIN-protected management key or the factory default.")
	yubiKeyTouchPolicy   = flag.String("yubikey-touch-policy", string(yubikey.TouchCached), "Whether the YubiKey must be touched to sign with a key made by --yubikey-generate-root: never, always, or cached (touch once per 15 seconds).")
	yubiKeyOverwriteSlot = flag.Bool("yubikey-overwrite", false, "Allow --yubikey-generate-root to replace a slot that already holds a certificate. The old key is destroyed.")

	version = flag.Bool("version", false, "Print version and build information, then exit.")
)

const (
	algorithmRSA          = "RSA"
	algorithmECDSA        = "ECDSA"
	defaultCodeSignTarget = "windows10"

	yubiKeyPINEnv           = "CERTTOOL_YUBIKEY_PIN"
	yubiKeyManagementKeyEnv = "CERTTOOL_YUBIKEY_MANAGEMENT_KEY"
)

func main() {
	os.Exit(certtoolMain())
}

// certtoolMain runs the tool and returns the process exit code.
func certtoolMain() int {
	flag.Parse()
	logging.Init()

	if *version {
		fmt.Printf("certtool %s (built %s)\n", internal.Version(), internal.Buildstamp())
		return 0
	}

	if *target != "" && !*codeSigning {
		slog.Warn("--target is set but --code-sign is not; --target will be ignored")
	}

	if *namePrefix != "" && *chain == "" {
		slog.Warn("--name-prefix is set but --chain is not; --name-prefix will be ignored")
	}

	if err := validateModeFlags(); err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	if *yubiKeyGenerateRoot {
		return runYubiKeyGenerateRootMode()
	}

	if *exportSpec != "" && *useYubiKey {
		slog.Warn("--yubikey is set with --export-spec; the exported spec does not record the YubiKey issuer")
	}

	var issuer *certtool.Issuer
	if *useYubiKey && *exportSpec == "" {
		token, err := openYubiKey()
		if err != nil {
			slog.Error("certtool failed", "error", err)
			return 1
		}
		defer closeYubiKey(token)

		issuer, err = token.Issuer()
		if err != nil {
			slog.Error("certtool failed", "error", err)
			return 1
		}
		slog.Info("signing with YubiKey root CA", "serial", token.Serial(), "slot", *yubiKeySlot, "cn", issuer.Certificate.Subject.CommonName)
	}

	if *spec != "" {
		return runSpecMode(issuer)
	}

	if *chain != "" {
		return runChainMode(issuer)
	}

	if *exportSpec != "" {
		return runExportSpecMode()
	}

	args, err := argsFromFlags()
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}
	args.Issuer = issuer

	if err := generateAndWriteKeyPair(args); err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	return 0
}

func validateModeFlags() error {
	hasChain := *chain != ""
	hasSpec := *spec != ""
	if hasChain && hasSpec {
		return fmt.Errorf("--chain and --spec are mutually exclusive")
	}
	if *useYubiKey && *yubiKeyGenerateRoot {
		return fmt.Errorf("--yubikey and --yubikey-generate-root are mutually exclusive")
	}
	if *useYubiKey && (*parentPublicCertificate != "" || *parentPrivateKey != "") {
		return fmt.Errorf("--yubikey and --parent-public-certificate/--parent-private-key are mutually exclusive")
	}
	if *yubiKeyGenerateRoot && (hasChain || hasSpec || *exportSpec != "" || *codeSigning || *parentPublicCertificate != "" || *parentPrivateKey != "") {
		return fmt.Errorf("--yubikey-generate-root cannot be combined with --chain, --spec, --export-spec, --code-sign, or --parent-public-certificate/--parent-private-key")
	}
	if !*yubiKeyGenerateRoot && (*yubiKeyOverwriteSlot || *yubiKeyTouchPolicy != string(yubikey.TouchCached)) {
		return fmt.Errorf("--yubikey-touch-policy and --yubikey-overwrite only apply to --yubikey-generate-root")
	}
	if !*useYubiKey && !*yubiKeyGenerateRoot && (*yubiKeySerial != "" || *yubiKeySlot != yubikey.DefaultSlot || *yubiKeyPIN != "" || *yubiKeyManagementKey != "") {
		return fmt.Errorf("the --yubikey-* options need --yubikey or --yubikey-generate-root")
	}
	return nil
}

// openYubiKey opens the YubiKey selected by the --yubikey-* flags.
func openYubiKey() (*yubikey.Token, error) {
	cfg, err := yubiKeyConfig()
	if err != nil {
		return nil, err
	}
	return yubikey.Open(cfg)
}

// yubiKeyConfig builds the YubiKey configuration from the --yubikey-* flags,
// falling back to environment variables for the secrets.
func yubiKeyConfig() (yubikey.Config, error) {
	pin := *yubiKeyPIN
	if pin == "" {
		pin = os.Getenv(yubiKeyPINEnv)
	}
	managementKey := *yubiKeyManagementKey
	if managementKey == "" {
		managementKey = os.Getenv(yubiKeyManagementKeyEnv)
	}

	var serial uint64
	if *yubiKeySerial != "" {
		var err error
		if serial, err = strconv.ParseUint(*yubiKeySerial, 10, 32); err != nil {
			return yubikey.Config{}, fmt.Errorf("--yubikey-serial %q is not a valid serial number", *yubiKeySerial)
		}
	}

	return yubikey.Config{
		Serial:        uint32(serial),
		Slot:          *yubiKeySlot,
		PIN:           pin,
		PINPrompt:     promptYubiKeyPIN,
		ManagementKey: managementKey,
		BeforeSign: func() {
			slog.Info("signing with the YubiKey, touch it if it is blinking")
		},
	}, nil
}

func closeYubiKey(token *yubikey.Token) {
	if err := token.Close(); err != nil {
		slog.Warn("cannot close the YubiKey", "error", err)
	}
}

func promptYubiKeyPIN() (string, error) {
	fd := int(os.Stdin.Fd())
	if !term.IsTerminal(fd) {
		return "", fmt.Errorf("stdin is not a terminal, set --yubikey-pin or %s", yubiKeyPINEnv)
	}
	fmt.Fprint(os.Stderr, "YubiKey PIN: ")
	pin, err := term.ReadPassword(fd)
	fmt.Fprintln(os.Stderr)
	if err != nil {
		return "", err
	}
	return string(pin), nil
}

func runYubiKeyGenerateRootMode() int {
	touchPolicy, err := yubikey.ParseTouchPolicy(*yubiKeyTouchPolicy)
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	args, err := argsFromFlags()
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	token, err := openYubiKey()
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}
	defer closeYubiKey(token)

	slog.Info("generating root CA on YubiKey", "serial", token.Serial(), "slot", *yubiKeySlot)
	cert, err := token.GenerateRoot(args, touchPolicy, *yubiKeyOverwriteSlot)
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	if err := certtool.WriteCertificate(cert, *publicCertificate); err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}
	slog.Info("generated YubiKey root CA", "cn", cert.Subject.CommonName, "cert", *publicCertificate, "serial", token.Serial(), "slot", *yubiKeySlot)
	return 0
}

func parseChainFlag() ([]int, error) {
	parts := strings.Split(*chain, ",")
	widths := make([]int, len(parts))
	for i, p := range parts {
		p = strings.TrimSpace(p)
		v, err := strconv.Atoi(p)
		if err != nil {
			return nil, fmt.Errorf("--chain value %q is not a valid integer", p)
		}
		widths[i] = v
	}
	return widths, nil
}

func runChainMode(issuer *certtool.Issuer) int {
	widths, err := parseChainFlag()
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	specs, err := certtool.ChainToSpec(widths, *commonName, *organization, *namePrefix)
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	if *exportSpec != "" {
		return writeSpecFile(specs)
	}

	return generateAndLogResults(specs, issuer)
}

func runExportSpecMode() int {
	specs, err := flagsToSpec()
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}
	return writeSpecFile(specs)
}

func flagsToSpec() ([]certtool.CertificateSpec, error) {
	portList, err := splitInts(*ports)
	if err != nil {
		return nil, err
	}

	cn := *commonName
	if cn == "" {
		cn = *organization
	}

	s := certtool.CertificateSpec{
		CommonName:           cn,
		CertificateAuthority: *ca,
		CodeSigning:          *codeSigning,
		Target:               *target,
		PFXPassword:          *pfxPassword,
		KeyType:              *keyType,
		Validity:             validity.String(),
		Organization:         *organization,
		OrganizationalUnit:   *organizationalUnit,
		Country:              *country,
		Locality:             *locality,
		Province:             *province,
		Hostnames:            splitStrings(*hostnames),
		Ports:                portList,
	}
	return []certtool.CertificateSpec{s}, nil
}

func writeSpecFile(specs []certtool.CertificateSpec) int {
	data, err := certtool.MarshalSpec(specs)
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}
	if err := os.WriteFile(filepath.Clean(*exportSpec), data, 0o600); err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}
	slog.Info("spec written", "path", *exportSpec)
	return 0
}

func generateAndLogResults(specs []certtool.CertificateSpec, issuer *certtool.Issuer) int {
	results, err := certtool.GenerateFromSpecWithIssuer(specs, *outputDir, issuer)
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	for _, r := range results {
		if r.PFXPath != "" {
			slog.Info("generated certificate", "cn", r.CommonName, "cert", r.CertPath, "key", r.KeyPath, "pfx", r.PFXPath)
		} else {
			slog.Info("generated certificate", "cn", r.CommonName, "cert", r.CertPath, "key", r.KeyPath)
		}
	}
	return 0
}

func runSpecMode(issuer *certtool.Issuer) int {
	specs, err := certtool.ReadSpec(*spec)
	if err != nil {
		slog.Error("certtool failed", "error", err)
		return 1
	}

	if *exportSpec != "" {
		return writeSpecFile(specs)
	}

	return generateAndLogResults(specs, issuer)
}

func generateAndWriteKeyPair(args *certtool.Args) error {
	kp, err := certtool.GenerateKeyPair(args)
	if err != nil {
		return err
	}
	if len(kp.PFX) > 0 {
		return certtool.WritePFX(kp, *pfxOutput)
	}
	return certtool.WriteKeyPair(kp, *publicCertificate, *privateKey)
}

func argsFromFlags() (*certtool.Args, error) {
	var parent *certtool.KeyPair

	// Detect if --key-type was explicitly set by the user (not just the default value).
	// flag.Visit only visits flags explicitly set via flag.Parse or flag.Set.
	var keyTypeExplicitlySet bool
	flag.Visit(func(f *flag.Flag) {
		if f.Name == "key-type" {
			keyTypeExplicitlySet = true
		}
	})

	var kt *certtool.KeyType
	if keyTypeExplicitlySet || !*codeSigning {
		algorithm, keyLength, err := stringToKeyType(*keyType)
		if err != nil {
			return nil, err
		}
		kt = &certtool.KeyType{Algorithm: algorithm, KeyLength: keyLength}

		// Warn if the user explicitly chose ECDSA for a Windows 7 target.
		if *codeSigning && strings.ToUpper(algorithm) == algorithmECDSA {
			effectiveTarget := *target
			if effectiveTarget == "" {
				effectiveTarget = defaultCodeSignTarget
			}
			if profile, profErr := certtool.GetProfile(effectiveTarget); profErr == nil && profile.LegacyPFX {
				slog.Warn("ECDSA code signing certs are not supported by Windows 7 signtool.exe; proceeding with user-specified key type")
			}
		}
	}
	// If kt is nil and codeSigning is true, fillDefaults resolves the key type from the profile.

	var err error
	if *parentPublicCertificate != "" {
		parent, err = certtool.ReadKeyPairFromFile(*parentPublicCertificate, *parentPrivateKey)
		if err != nil {
			return nil, err
		}
	}

	if *validity <= 0 {
		return nil, fmt.Errorf("--validity must be a positive duration, got %s", *validity)
	}

	portList, err := splitInts(*ports)
	if err != nil {
		return nil, err
	}
	return &certtool.Args{
		CA:                 *ca,
		CommonName:         *commonName,
		Country:            *country,
		Organization:       *organization,
		OrganizationalUnit: *organizationalUnit,
		Locality:           *locality,
		Province:           *province,
		Validity:           *validity,
		Hostnames:          splitStrings(*hostnames),
		Ports:              portList,
		KeyType:            kt,
		ParentKeyPair:      parent,
		CodeSigning:        *codeSigning,
		Target:             *target,
		PFXPassword:        *pfxPassword,
	}, nil
}

func stringToKeyType(keyType string) (string, int, error) {
	if keyType == "" {
		return algorithmRSA, 2048, nil
	}
	switch parseKeyTypeKeyName(keyType) {
	case algorithmRSA:
		return parseKeyTypeName(keyType, 2048, []int{2048, 4096})
	case algorithmECDSA:
		return parseKeyTypeName(keyType, 521, []int{224, 256, 384, 521})
	}
	return "", 0, fmt.Errorf("'%s' is not a valid key type", keyType)
}

func parseKeyTypeKeyName(keyTypeName string) string {
	parts := strings.Split(strings.ToUpper(keyTypeName), "-")
	if len(parts) > 0 {
		return parts[0]
	}
	return algorithmRSA
}

func parseKeyTypeName(keyTypeName string, defaultLength int, validValues []int) (string, int, error) {
	parts := strings.Split(strings.ToUpper(keyTypeName), "-")
	if len(parts) > 2 {
		return "", 0, fmt.Errorf("key type '%s' is not valid", keyTypeName)
	}
	if len(parts) == 0 {
		return "", 0, fmt.Errorf("key type does not have a name")
	}

	algorithm := parts[0]
	keyLength := ""
	if len(parts) == 2 {
		keyLength = parts[1]
	}

	if keyLength == "" {
		return algorithm, defaultLength, nil
	}
	length, err := strconv.Atoi(parts[1])
	if err != nil {
		return "", 0, fmt.Errorf("key type '%s' does not have a valid %s key length", keyTypeName, algorithm)
	}
	if slices.Contains(validValues, length) {
		return algorithm, length, nil
	}

	return "", 0, fmt.Errorf("key type '%s' does not have a valid %s key length", keyTypeName, algorithm)
}

func splitStrings(csv string) []string {
	if csv == "" {
		return nil
	}
	parts := strings.Split(csv, ",")
	for i, p := range parts {
		parts[i] = strings.TrimSpace(p)
	}
	return parts
}

func splitInts(csv string) ([]int, error) {
	if csv == "" {
		return nil, nil
	}
	vals := splitStrings(csv)
	result := make([]int, len(vals))
	for i, v := range vals {
		iv, err := strconv.Atoi(v)
		if err != nil {
			return nil, fmt.Errorf("cannot convert %q to an integer, %w", v, err)
		}
		if iv < 1 || iv > 65535 {
			return nil, fmt.Errorf("port %d is not valid, must be between 1 and 65535", iv)
		}
		result[i] = iv
	}
	return result, nil
}
